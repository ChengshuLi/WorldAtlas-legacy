/* Bind one Mary143 dual-role stage to the accepted bounded GSHHG physical template. */
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';

const root=fs.realpathSync(process.cwd());
const STAGE_COMMIT='1ddddf52ca62de5f5de0789c0eb28961741da2ed';
const STAGE_PATH='coordination/engineering/tkm-mary143-physical-001/original-stage-inputs.json';
const TARGET_COMMIT='6fc2e403c57d4b3e50341670447747b1053f4765';
const TARGET_PATH='data/geography/part-23.json';
const TEMPLATE_COMMIT='547de322e44015f4a7639e8570c7dccb0b1a882b';
const TEMPLATE_PATH='coordination/engineering/tkm-baherden53-source-fit-20261026/config/physical-002.json';
const RUNTIME_PATH='/workspace/shared/worldatlas-TKM-Baherden53-runtime-inventory-004-20261027.json';
const SOURCE_PATH='/workspace/shared/worldatlas-TKM1759-qualification-20261026/.private/full-2009-source.geojson';
const DEST='coordination/engineering/tkm-mary143-physical-001/config/physical-001.json';
const need=(ok,message)=>{if(!ok) throw Error(message);};
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
const {pinReader}=await import(pathToFileURL(path.join(root,'scripts/prepare-delivery-handoff.mjs')));
const reader=pinReader(root);
const stagePin=reader.pin(STAGE_COMMIT,STAGE_PATH), stage=JSON.parse(reader.read(stagePin));
const targetPin=reader.pin(TARGET_COMMIT,TARGET_PATH), target=JSON.parse(reader.read(targetPin));
const sourceRaw=fs.readFileSync(SOURCE_PATH), source=JSON.parse(sourceRaw);
need(sourceRaw.length===271437&&digest(sourceRaw)==='0d0b3745e275bfadb1d0137fbca014b56f2ed72cb83b0a98dd0e2f0632e7c507','Original full-source body identity changed');
need(targetPin.bytes===4962410&&targetPin.sha256==='d61082ccd69b319723fadc4cad582b8d5c8a8ced3e50b4f90f00b4eb17e6a9c2','Selected current target part identity changed');
need(stagePin.bytes===5670&&stagePin.sha256==='9108c75e8bbc473d99d094f2f6337dd82d3030aaebd4672b7fa9300f261d2015','Committed Mary stage input differs');
need(stage.length===1&&stage[0].family==='gb:TKM:ADM2'&&stage[0].target==='gb:TKM:ADM2:10190150B47066979897930','Stage target/family changed');
const direct=source.features.filter(f=>f.properties?.shapeID==='10190150B47066979897930');
const sibling=source.features.filter(f=>f.properties?.shapeID==='10190150B21853413573592');
const selected=target.features.filter(f=>f.properties?.id==='gb:TKM:ADM2:10190150B47066979897930');
need(direct.length===1&&sibling.length===1&&selected.length===1,'Mary direct/sibling/source target identities ambiguous');
need(JSON.stringify(stage[0].consumed)===JSON.stringify(direct[0]),'Consumed geometry/attributes differ from exact original direct-Mary feature');
need(stage[0].selected.id===selected[0].properties.id&&JSON.stringify(stage[0].selected.geometry)===JSON.stringify(selected[0].geometry),'Selected geometry differs from exact current direct-Mary part feature');
need(stage[0].selected.id!=='gb:TKM:ADM2:10190150B21853413573592','Same-name sibling is not selected');
const templatePin=reader.pin(TEMPLATE_COMMIT,TEMPLATE_PATH), template=JSON.parse(reader.read(templatePin));
need(template.version===1&&template.physical?.version===1&&template.physical.inputs.length===25,'Accepted physical template differs');
const oldStage=template.physical.roles.stages, inputs=new Map(template.physical.inputs.map(pin=>[pin.path,pin]));
need(inputs.has(oldStage),'Template stage input pin missing');
inputs.delete(oldStage); inputs.set(STAGE_PATH,stagePin);
const physical=structuredClone(template.physical);
physical.inputs=[...inputs.values()].sort((a,b)=>a.path.localeCompare(b.path));
physical.roles.stages=STAGE_PATH;
need(physical.inputs.length===25&&physical.inputs.filter(pin=>pin.path===STAGE_PATH).length===1,'Physical inventory changed outside intended stage binding');
const runtimeRaw=fs.readFileSync(RUNTIME_PATH), runtime=JSON.parse(runtimeRaw);
need(runtime.files.length===207&&runtime.method?.runtime_path_function==='runtime_paths','Pinned existing physical runtime inventory differs');
for(const pin of runtime.files){const raw=fs.readFileSync(pin.path);need(raw.length===pin.bytes&&digest(raw)===pin.sha256,'Runtime file identity changed: '+pin.path);}
need(runtime.files.some(pin=>pin.path===runtime.python.path&&pin.bytes===runtime.python.bytes&&pin.sha256===runtime.python.sha256),'Runtime executable pin missing');
physical.runtime={python:runtime.version,numpy:runtime.numpy,shapely:runtime.shapely,geos:runtime.geos};
const config={version:1,physical,runtime_inventory:{python:runtime.python,files:runtime.files}};
const dest=path.join(root,DEST);need(!fs.existsSync(dest),'Physical config destination is not fresh');
fs.mkdirSync(path.dirname(dest),{recursive:true});const body=Buffer.from(JSON.stringify(config,null,2)+'\n');fs.writeFileSync(dest,body,{flag:'wx'});
console.log(JSON.stringify({path:DEST,bytes:body.length,sha256:digest(body),stage:stagePin,target:targetPin,template:{commit:TEMPLATE_COMMIT,path:TEMPLATE_PATH,sha256:templatePin.sha256},runtime:{path:RUNTIME_PATH,bytes:runtimeRaw.length,sha256:digest(runtimeRaw),files:runtime.files.length},physical_inputs:physical.inputs.length,source_body:{path:SOURCE_PATH,bytes:sourceRaw.length,sha256:digest(sourceRaw)}}));
